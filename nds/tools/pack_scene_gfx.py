"""Precompose the authorized ep2d3 slice into fully resident RGB15 tile banks.

Original files are read-only. Every frame uses AnimRenderer's common 1/5 stage;
iss is generated by IssText from Fusion Pixel dots and measured/fitted positions,
never loaded from an is*.png texture. No changes to the old asset/audio packs.
"""
from __future__ import annotations
import argparse
from collections import OrderedDict
import hashlib
import json
from pathlib import Path
import struct
import sys

import numpy as np
from PIL import Image, ImageDraw

ROOT=Path(__file__).resolve().parents[2]
LAB=ROOT/'experiments/asset_lab'
sys.path.insert(0,str(LAB))
from anim_renderer import AnimRenderer, DEFAULT_GAME
from anim_story import build_story
from iss_text import IssText
from anim_text import SceneText
from portrait_preview import OUT as FONT_OUT

HEADER=struct.Struct('<8s8I')
GROUP=struct.Struct('<8I')
BANK=struct.Struct('<6I')
MAP_TILES=32*18
MAX_HEAP=2400*1024
NAMES=('black','carfix','red','hands','mirror','iss','window')
PARAMETERS=((1,1,False),(1,1,False),(30,6,True),(27,1,False),
            (36,3,True),(10,3,True),(6,6,True))


def sha(data): return hashlib.sha256(data).hexdigest()


def fnv(data):
    value=2166136261
    for b in data: value=((value^b)*16777619)&0xffffffff
    return value


def words(image):
    q=(np.asarray(image,dtype=np.uint16)*31+127)//255
    return (q[:,:,0]|(q[:,:,1]<<5)|(q[:,:,2]<<10)|0x8000).astype('<u2')


def build(game, output, manifest, contact=None):
    story=build_story(game)
    renderer=AnimRenderer(game,iss_mode='text')
    events={event['line']:event for event in story['events'] if event['kind']=='show'}
    def layers(lines):
        return [dict(events[line],name=events[line]['image'],start=0.) for line in lines]
    red=layers((614,615,616,617,619))
    compositions={'black':[dict(name='black',start=0.,properties={})],
                  'carfix':[dict(name='carfix',start=0.,properties={})],
                  'red':red,'hands':red+layers((620,)),
                  'mirror':layers((653,654,655,656)),
                  'iss':[dict(name='iss',start=0.,properties={})],
                  'window':layers((792,))}
    # red and hands intentionally share one dictionary and both sets of maps.
    bank_names=('black','carfix','red_hands','mirror','iss','window')
    bank_of={'black':0,'carfix':1,'red':2,'hands':2,'mirror':3,'iss':4,'window':5}
    banks=[dict(name=name,tiles=OrderedDict(),maps=[]) for name in bank_names]
    groups=[];used_images=set();thumbnails=[]
    for group_id,(name,(count,step,loop)) in enumerate(zip(NAMES,PARAMETERS)):
        bank_id=bank_of[name];bank=banks[bank_id]
        entry=dict(name=name,id=group_id,bank=bank_id,first_frame=len(bank['maps']),
                   frame_count=count,step_ticks=step,loop=loop,
                   source_lines={'black':[605],'carfix':[285],
                                 'red':[614,615,616,617,619],
                                 'hands':[614,615,616,617,619,620,624,626],
                                 'mirror':[653,654,655,656],
                                 'iss':[603],'window':[792]}[name],
                   golden_frames=[])
        for frame in range(count):
            image=renderer.render(compositions[name],frame*step/60.)
            if renderer.metadata['missing']: raise ValueError(renderer.metadata['missing'])
            for layer in renderer.metadata['layers']:
                if layer['selected'] in renderer.index: used_images.add(layer['selected'])
            screen=words(image);raw=screen.tobytes()
            entry['golden_frames'].append(dict(frame=frame,ticks=frame*step,
                                              sha256=sha(raw),fnv1a32=fnv(raw)))
            stage=screen[24:168]
            tile_map=[]
            for y in range(0,144,8):
                for x in range(0,256,8):
                    tile=stage[y:y+8,x:x+8].tobytes()
                    index=bank['tiles'].setdefault(tile,len(bank['tiles']))
                    tile_map.append(index)
            bank['maps'].append(struct.pack('<576H',*tile_map))
            if frame=={'black':0,'carfix':0,'red':13,'hands':10,'mirror':17,'iss':9,'window':3}[name]:
                thumbnails.append((name,image.copy()))
        groups.append(entry)
    table_bytes=HEADER.size+len(groups)*GROUP.size+len(banks)*BANK.size
    payload=bytearray();bank_records=[];bank_info=[]
    for bank_id,bank in enumerate(banks):
        raw=b''.join(bank['tiles'])+b''.join(bank['maps'])
        record=(table_bytes+len(payload),len(raw),len(bank['tiles']),len(bank['maps']),fnv(raw),0)
        bank_records.append(record);payload.extend(raw)
        bank_info.append(dict(id=bank_id,name=bank['name'],offset=record[0],bytes=len(raw),
                              tile_count=record[2],map_count=record[3],fnv1a32=record[4],sha256=sha(raw)))
    if len(payload)>MAX_HEAP: raise ValueError(f'resident images exceed budget: {len(payload)}')
    file=bytearray(HEADER.pack(b'ZATOGFX1',1,256,144,24,len(groups),len(banks),table_bytes+len(payload),0))
    for g in groups:
        file.extend(GROUP.pack(g['id'],g['bank'],g['first_frame'],g['frame_count'],g['step_ticks'],int(g['loop']),0,0))
    for record in bank_records: file.extend(BANK.pack(*record))
    file.extend(payload)
    if len(file)>=13000000: raise ValueError('graphics pack exceeds new ROM budget')
    sources=[dict(path='game/'+renderer.index[name].relative_to(game).as_posix(),
                  sha256=sha(renderer.index[name].read_bytes())) for name in sorted(used_images)]
    # Export the actual native glyph dots as well as IssText word placements and
    # per-frame word counts; this documents a reproducible text-generated effect.
    fonts=SceneText();atlas=[]
    for size in (8,12):
        mask=Image.new('L',(size*3,size));x=0
        for char in 'is':
            glyph,advance=fonts.glyph(char,size);mask.paste(glyph,(x,0));x+=advance
        mask=mask.crop(mask.getbbox());bits=(np.asarray(mask)>0).astype(np.uint8)
        atlas.append(dict(font_size=size,width=mask.width,height=mask.height,
                          dot_rows=[''.join(str(int(bit)) for bit in row) for row in bits],
                          bitmap_sha256=sha(bits.tobytes())))
    result=dict(format='ZATOGFX1',version=1,path=output.relative_to(ROOT).as_posix() if output.is_relative_to(ROOT) else str(output),
                width=256,height=144,screen_width=256,screen_height=192,position=[0,24],
                pixel_format='opaque A1B5G5R5 little endian',ticks_per_second=60,
                groups=groups,banks=bank_info,bytes=len(file),sha256=sha(file),
                memory=dict(resident_image_heap_bytes=len(payload),peak_image_heap_bytes=len(payload),
                            fixed_index_bss_bytes=32*32+16*24,loader_chunk_max_bytes=4096,
                            loader_staging_heap_bytes=0,frame_heap_bytes=0,
                            frame_file_reads=0,select_file_reads=0,
                            all_banks_loaded_at_open=True),
                sources=sources,source_story_sha256=story['source_sha256'],
                generator_sources=[dict(path=p.relative_to(ROOT).as_posix(),sha256=sha(p.read_bytes()))
                                   for p in (LAB/'anim_renderer.py',LAB/'iss_text.py',LAB/'anim_text.py')],
                font_sources=[dict(path=(FONT_OUT/f'font_{size}px.zfn').relative_to(ROOT).as_posix(),
                                   sha256=sha((FONT_OUT/f'font_{size}px.zfn').read_bytes())) for size in (8,12)],
                iss=dict(metadata=IssText().metadata,glyph_atlas=atlas,
                         original_is_textures_read=False,
                         generation='Offline IssText point-font/coordinate accumulation including overlap gain and oldest-pixel tail dimming.'),
                phase_origin='hands and red share the original show origin; hands is clamped, red continues at tick 27 after hide hands.',
                composition='Existing AnimRenderer RGB15 reference: common 1280x720 / 5, alpha/add/flip/ATL shaking and easein hands zoom baked before RGB15.',
                approximation='Pillow RGBA Box/bilinear sampling and native dot iss fitting follow the reviewed Python preview; not source-engine pixel identity.')
    output.parent.mkdir(parents=True,exist_ok=True);output.write_bytes(file)
    manifest.parent.mkdir(parents=True,exist_ok=True)
    manifest.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    if contact:
        sheet=Image.new('RGB',(256*4,216*2),(32,32,32));draw=ImageDraw.Draw(sheet)
        for index,(name,image) in enumerate(thumbnails):
            x=(index%4)*256;y=(index//4)*216
            draw.text((x+6,y+4),name,fill='white');sheet.paste(image,(x,y+24))
        contact.parent.mkdir(parents=True,exist_ok=True);sheet.save(contact)
    return result


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game',type=Path,default=DEFAULT_GAME)
    parser.add_argument('--output',type=Path,default=ROOT/'nds/nitrofs/scene/gfx.bin')
    parser.add_argument('--manifest',type=Path,default=ROOT/'nds/artifacts/scene_gfx_manifest.json')
    parser.add_argument('--contact',type=Path)
    args=parser.parse_args()
    result=build(args.game.resolve(),args.output.resolve(),args.manifest.resolve(),args.contact)
    print(json.dumps(dict(bytes=result['bytes'],resident=result['memory']['resident_image_heap_bytes'],
                          groups=len(result['groups']),frames=sum(g['frame_count'] for g in result['groups']),
                          banks=[dict(name=b['name'],tiles=b['tile_count'],bytes=b['bytes']) for b in result['banks']]),indent=2))


if __name__=='__main__': main()
